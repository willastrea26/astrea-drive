-- =====================================================================
-- Astrea Drive — GPS sync run log
--
-- Run once in the Supabase SQL Editor. Every time the netstar edge
-- function's sync-odometers action runs — nightly cron, weekly deep
-- resync, or someone clicking a button — it records one row here: when,
-- what triggered it, and whether it succeeded. The dashboard reads the
-- latest "cron"-sourced row to show whether the automatic nightly sync
-- is actually running, without needing access to pg_cron's own tables.
-- =====================================================================

create table if not exists public.sync_log (
  id                  bigint generated by default as identity primary key,
  source              text not null,              -- 'cron' | 'manual' — which Authorization role made the call
  depth               text,                        -- 'recent' | 'full'
  quick               boolean not null default false,
  ok                  boolean not null,
  updated             integer,
  verified            integer,
  "dailyRecorded"      integer,
  "tripStatsRecorded"  integer,
  "workHoursRecorded"  integer,
  error               text,
  "ranAt"              timestamptz not null default now()
);

create index if not exists sync_log_source_ran_idx on public.sync_log (source, "ranAt" desc);

revoke all on table public.sync_log from anon;
grant select on table public.sync_log to authenticated;
alter table public.sync_log enable row level security;
create policy "approved users read sync log" on public.sync_log
  for select to authenticated using (is_approved());

-- Insert one log row. SECURITY DEFINER so the edge function needs no
-- service-role key, matching the rest of the Netstar write path.
create or replace function public.record_sync_log(
  p_source text, p_depth text, p_quick boolean, p_ok boolean,
  p_updated integer, p_verified integer,
  p_daily_recorded integer, p_trip_stats_recorded integer, p_work_hours_recorded integer,
  p_error text
) returns bigint
language sql
security definer
set search_path = public
as $$
  insert into public.sync_log
    (source, depth, quick, ok, updated, verified, "dailyRecorded", "tripStatsRecorded", "workHoursRecorded", error)
  values
    (p_source, p_depth, coalesce(p_quick, false), p_ok, p_updated, p_verified, p_daily_recorded, p_trip_stats_recorded, p_work_hours_recorded, p_error)
  returning id;
$$;

revoke all on function public.record_sync_log(text, text, boolean, boolean, integer, integer, integer, integer, integer, text) from public;
grant execute on function public.record_sync_log(text, text, boolean, boolean, integer, integer, integer, integer, integer, text) to anon, authenticated;

